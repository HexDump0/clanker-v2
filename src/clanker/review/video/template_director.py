def _fallback_card(reason: str, inputs: RejectVideoInputs, repo: Repo | None) -> SceneSpec:
    ctx = inputs.ctx
    title, caption, fix = FALLBACK_CARDS.get(
        reason, ("This needs a fix", "See the review message for details.", "See the review")
    )
    if reason.startswith(("demo_", "bad_hosting", "itch_", "bot_", "needs_api")):
        lines = [f"demo:  {ctx.demo_url or '(not set)'}"]
    elif reason.startswith(("readme_", "ai_readme", "no_readme")):
        lines = [f"README:  {ctx.readme_url or '(not set)'}"]
    elif reason.startswith("banner_"):
        lines = [f"banner:  {inputs.banner_url or '(default)'}"]
    elif reason == "missing_build" and repo:
        lines = [f"releases:  {repo.releases_url}"]
    elif reason == "untitled":
        lines = [f"name:  {inputs.project_name or 'untitled'}"]
    else:
        lines = [f"repo:  {inputs.repo_url or ctx.repo_url or '(not set)'}"]
    return SceneSpec(
        id=reason.replace("_", "-"),
        reason=reason,
        title=title,
        caption=caption,
        card_lines=lines,
        fix=fix,
    )


def evidence_for(specs: Sequence[SceneSpec]) -> list[VideoEvidence]:
    """Live-capture scenes as VideoEvidence for the existing capture step."""
    return [
        VideoEvidence(id=s.id, check=s.reason, url=s.url, finding=s.caption) for s in specs if s.url
    ]


async def render_text_card(spec: SceneSpec, output_dir: Path) -> EvidenceCapture:
    """Render a text-card 'screenshot' locally (no network): a plain text page, so it looks
    like any other tab in the browser-style video."""
    from playwright.async_api import async_playwright

    output_dir.mkdir(parents=True, exist_ok=True)
    path = output_dir / f"{spec.id}.png"
    lines = "".join(f"<div class='line'>{html.escape(line)}</div>" for line in spec.card_lines)
    document = f"""<!doctype html><html><head><meta charset="utf-8"><style>
html,body{{margin:0;width:{VIEWPORT["width"]}px;height:{VIEWPORT["height"]}px;background:#fff;
font-family:"DejaVu Sans Mono","Liberation Mono",ui-monospace,monospace;color:#111}}
.wrap{{position:absolute;left:8px;top:8px;right:8px}}
.line{{font-size:15px;line-height:1.5;white-space:pre-wrap;word-break:break-all}}
</style></head><body><div class="wrap">{lines}</div>
</body></html>"""
    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True, args=["--no-sandbox"])
        page = await browser.new_page(viewport=VIEWPORT)
        await page.set_content(document)
        await page.screenshot(path=str(path))
        await browser.close()
    return EvidenceCapture(
        evidence_id=spec.id,
        requested_url="",
        final_url="",
        captured_at=datetime.now(UTC),
        screenshot_path=path,
        viewport_width=VIEWPORT["width"],
        viewport_height=VIEWPORT["height"],
    )


HEADLINES = [
    "A few things to fix before reshipping",
    "Almost there, a few fixes first",
    "Not quite ready yet",
]


class TemplateDirector:
    """Director-protocol implementation with zero model calls."""

    model_calls = 0

    def __init__(self, specs: Sequence[SceneSpec], seed: str) -> None:
        self._specs = {s.id: s for s in specs}
        self._rng = random.Random(int(hashlib.sha256(seed.encode()).hexdigest()[:16], 16))

    async def direct(
        self,
        project: VideoProject,
        evidence: Sequence[VideoEvidence],
        captures: Sequence[EvidenceCapture],
    ) -> VideoPlan:
        captured = {c.evidence_id for c in captures}
        scenes = [
            DirectedScene(
                evidence_id=s.id,
                role=SceneRole.PRIMARY,
                title=s.title[:80],
                explanation=s.caption[:260],
                highlight_text=s.highlight,
            )
            for s in self._specs.values()
            if s.id in captured
        ]
        count = len(scenes)
        return VideoPlan(
            headline=self._rng.choice(HEADLINES),
            summary=(
                "One thing to fix, then reship."
                if count == 1
                else f"{count} things to fix, then reship."
            ),
            scenes=scenes,
        )
